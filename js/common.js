/* ---------------------------------------------------------
   1. 動きを減らす設定
   --------------------------------------------------------- */

// window.matchMedia は「端末の設定」を調べる命令。
// 端末で「視差効果を減らす（動きを減らす）」が選ばれていたら true になる。
// そのときは、アニメーションをやめて最初から最後の状態を見せる。
const REDUCE_MOTION = window.matchMedia("(prefers-reduced-motion: reduce)").matches;

// アニメーションの長さ（ミリ秒。1000ミリ秒 = 1秒）。
// 「条件 ? Aの値 : Bの値」は、条件が true なら A、false なら B になる書き方（三項演算子）。
const ANIMATION_MS = REDUCE_MOTION ? 1 : 3000;


/* ---------------------------------------------------------
   2. アニメーションの進み具合を計算する関数
   --------------------------------------------------------- */

// 始まった時刻（start）から今（now）までに、全体（duration）の何割が進んだかを 0〜1 で返す。
//   例：3秒のアニメーションで1.5秒たったら 0.5
// Math.min(…, 1) で 1 より大きくならないように、Math.max(0, …) で 0 より小さくならないようにしている。
// （始まった直後は、時刻のずれで少しだけマイナスになることがあるため）
function progressOf(start, duration, now) {
  return Math.max(0, Math.min((now - start) / duration, 1));
}

// 進み具合（0〜1）を「最後はゆっくり止まる」動きに変える。
// そのまま使うと一定の速さで動くが、これを通すと自然な止まり方になる。
function easeOut(t) {
  return 1 - Math.pow(1 - t, 3);
}
